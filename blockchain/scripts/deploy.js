// Deploys BugBounty to the local Hardhat node and registers the same demo consortium
// as the web app. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

async function main() {
  const signers = await hre.ethers.getSigners();
  const [council] = signers;

  const bounty = await hre.ethers.deployContract("BugBounty", [], council);
  await bounty.waitForDeployment();
  const address = await bounty.getAddress();
  console.log(`BugBounty deployed to ${address} by the Disclosure Council ${council.address}`);

  // Companies are admitted by the Council (permissioned) ...
  const companies = [
    [signers[1], "PaySecure Bank (demo)"],
    [signers[2], "CampusCloud"],
  ];
  for (const [signer, name] of companies) {
    await (await bounty.registerCompany(signer.address, name)).wait();
    console.log(`  company     ${name.padEnd(24)} ${signer.address}`);
  }
  // ... researchers register themselves (permissionless). Account 5 (kernel_kim) is left
  // unregistered so the demo can show self-registration in the web app.
  const researchers = [
    [signers[3], "0xAnaya"],
    [signers[4], "nullbyte_ravi"],
  ];
  for (const [signer, handle] of researchers) {
    await (await bounty.connect(signer).registerResearcher(handle)).wait();
    console.log(`  researcher  ${handle.padEnd(24)} ${signer.address}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
